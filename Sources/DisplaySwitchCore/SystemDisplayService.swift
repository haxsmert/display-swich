import CoreGraphics

/// 把所有与系统显示子系统的副作用交互藏在协议后,便于注入测试。
public protocol SystemDisplayService {
    /// 私有断开符号是否可用;不可用时(如未来 macOS 改名/移除)应禁用开关并提示,而非静默失败。
    var isSupported: Bool { get }
    /// 当前所有活跃屏(含内建屏)。
    func activeDisplays() -> [DisplayInfo]
    /// 这台机器是否**具备**内建屏面板(便携机即便合盖、内建屏不活跃也算);
    /// 用于「关到全黑后能否开盖恢复」的兜底判定。
    func hasBuiltInDisplay() -> Bool
    /// 物理连着的外接屏数量 —— 数**带 EDID 的显示传输节点**。这是本 app 唯一的物理连接真相。
    ///
    /// 返回 `nil` 表示**查不到**(查询失败),与「确实一块都没接」(`0`)是两回事:
    /// 混淆二者会让对账把还连着的屏当成已拔走,故必须可区分。
    ///
    /// 必要性:被软件关掉的屏在 CoreGraphics 层与被拔掉的屏**完全同形**——都从 online 列表消失、
    /// UUID 也解析不出(实测)。只有 IOKit 还留着那条物理连接,故用它区分
    /// 「我关的(该留在菜单里等你开回来)」与「已经拔掉的(该从菜单消失)」。
    ///
    /// 为什么必须是 EDID 判据,曾经的 framebuffer 判据(`DisplayWidth` 键)已被删除——它有两个致命缺陷,
    /// 都是实测撞出来的:
    ///   - **滞后**(2026-09-07):拔线的内核通知到达那一刻它仍报着拔线前的 2 块屏,
    ///     约 3.5 秒后才归零;而救援恰好发生在通知到达那一刻,拿滞后的数字判断等于不救。
    ///   - **数不到被禁用的屏**(2026-09-18):屏一被关,`DisplayWidth` 键就消失。
    ///     两块外接屏关掉其中一块时它报 1(EDID 判据报 2),据此算出「没有位置」,
    ///     把一块还连着的屏从菜单里藏了起来,用户再也点不开。
    /// 它的文档却一直写着「不受本 app 软件断开影响」——正是照着这句假承诺选错了判据。
    ///
    /// 本判据的已知保守方向:某些屏 / 转接器可能不报 EDID,导致计数**偏小**。
    /// 偏小意味着「更容易认为屏还在、更容易显示出来」,是安全方向。
    func liveExternalCount() -> Int?

    /// 注册「显示器被物理拔掉」的**内核事件**监听(IOKit 服务终止通知),用于全黑救援。
    ///
    /// 为什么不用 CoreGraphics 的 `CGDisplayRegisterReconfigurationCallback`:
    /// 实测(2026-09-07 拔拓展坞现场)拔线**全程 0 次派发**——它只对配置变更(如改分辨率)
    /// 派发,对物理拔线不派发;同一刻 `CGGetActiveDisplayList` 还报着拔线前的屏数。
    /// 而 IOKit 的终止通知在拔线瞬间就到,且计数当场归零。
    ///
    /// 同一次拔线会连着回调多次(实测一次拔线来了 6 条),故 handler 必须幂等。
    func observeDisplayDisconnect(_ handler: @escaping () -> Void)

    /// 系统里**存在但未点亮**的显示器 ID —— 直接问系统要真相,不依赖本 app 的任何记账。
    ///
    /// 取自私有符号 `CGSGetDisplayList`:它是**唯一**能列出被禁用显示器的接口。
    /// 公开的 `CGGetOnlineDisplayList` 看不到它们(实测:被关掉的屏从 online 列表一并消失),
    /// 所以光靠公开 API,一块被关掉的屏在记账丢失后就再也找不回来了。
    ///
    /// 必要性:本 app 的关闭记录只活在内存里,进程一死就没了(崩溃 / 被强杀 / 注销);
    /// 而被关闭的状态留在 WindowServer 里**不会自己恢复**。于是那块屏既不在活跃列表、
    /// 也不在记账里,菜单上根本看不到 —— 彻底失联。2026-09-18 真实发生过。
    ///
    /// ⚠️ 返回的列表里混着**空槽位**(没接屏的接口),它们与真实被禁用的屏在这一层完全同形
    /// (都是 1×1、非活跃),无法区分。唯一的分辨方式是挨个尝试点亮:
    /// 实测真屏 0.5 秒内成功,空槽立刻返回错误 1001,**都不阻塞**,所以逐个试是安全的。
    ///
    /// 合盖时的内建屏**不计入**:它此刻不活跃是正常的,不是被关着,而且对它调点亮会阻塞约 20 秒。
    /// 返回 `nil` 表示私有符号不可用。
    func inactiveDisplayIDs() -> [CGDirectDisplayID]?

    /// 盖子当前是否合着(IOKit `IOPMrootDomain` 的 `AppleClamshellState`)。
    /// `nil` = 查不到 / 非便携机——查不到时按「没合盖」处理,宁可试一次,不要因为查询失败而不救。
    ///
    /// 为什么救援必须知道:**合盖时内建屏物理上不可用**,此刻对它调「点亮」不会立刻失败,
    /// 而是**阻塞约 20 秒**才超时返回 false(2026-09-18 事故现场实测)。5 次重试拖了 3 分半、
    /// 期间主线程被占满连菜单都点不开,而用户早已合盖离开。
    /// 正确做法是合盖时不做这种注定失败的尝试,等开盖——那才是内建屏重新可用的时刻。
    func isClamshellClosed() -> Bool?

    /// 注册「内建屏可能重新变得可用」的时刻:开盖、系统唤醒、屏幕唤醒。
    ///
    /// 这是全黑救援的**第二个触发源**,与拔线事件同等必要。只挂拔线是不够的——
    /// 真实动线是「拔坞 → 合盖 → 走人 → 到新地点开盖」:拔线那一刻盖子往往已经合上,
    /// 救援必然失败;而开盖时**不会再有任何拔线事件**,救援就永远没有第二次机会。
    /// (2026-09-18 事故:重试用尽后到新地点开盖,屏仍是黑的,只能强制重启。)
    ///
    /// 该事件源很频繁(每次电源状态变化都来),handler 必须幂等,且在无需救援时完全静默。
    func observeBuiltInMayBecomeAvailable(_ handler: @escaping () -> Void)

    /// 启用/断开某块屏,返回是否成功。
    func setEnabled(_ id: CGDirectDisplayID, _ on: Bool) -> Bool
}
